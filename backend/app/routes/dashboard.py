from fastapi import APIRouter, Depends, HTTPException, Query
from typing import Dict, Any, List, Optional
from app.services.auth import get_current_user
from app.services.database import get_supabase_client
import datetime

router = APIRouter()

@router.get("/summary")
async def get_dashboard_summary(user_id: str = Depends(get_current_user), vault_id: Optional[str] = Query(None)):
    """
    Returns aggregated dashboard metrics and recent user activity.
    Optionally scoped to a specific vault via vault_id query param.
    """
    client = get_supabase_client()
    
    try:
        # Aggregations
        encrypted_assets = 0
        active_nominees = 0
        verified_documents = 0
        notarizations = 0
        
        # 1. Count Total Encrypted Assets — scoped to vault if provided
        if vault_id:
            # Count 1 for the vault itself
            vault_res = client.table("vaults").select("id", count="exact").eq("id", vault_id).execute()
            encrypted_assets = vault_res.count if vault_res.count else 0
        else:
            vaults_res = client.table("vaults").select("id", count="exact").eq("user_id", user_id).execute()
            if vaults_res.count is not None:
                encrypted_assets = vaults_res.count
            
        profiles_res = client.table("user_secure_profiles").select("id", count="exact").eq("user_id", user_id).execute()
        if profiles_res.count is not None:
            encrypted_assets += profiles_res.count
            
        # 2. Count active nominees — scoped to vault if provided
        if vault_id:
            nominees_res = client.table("nominees").select("id", count="exact").eq("vault_id", vault_id).execute()
            if nominees_res.count is not None:
                active_nominees = nominees_res.count
        elif encrypted_assets > 0:
            vaults_data = client.table("vaults").select("id").eq("user_id", user_id).execute()
            vault_ids = [v["id"] for v in vaults_data.data]
            
            if vault_ids:
                nominees_res = client.table("nominees").select("id", count="exact").in_("vault_id", vault_ids).execute()
                if nominees_res.count is not None:
                    active_nominees = nominees_res.count
                    
        # 3. Verified Docs / Notarizations mappings (Placeholder mappings based on future feature modules)
        # Assuming there's a documents table or verification table. Default to 0 until implemented.
        # ...
        
        # Fetch Recent Activity
        activity_res = client.table("user_activities").select("*").eq("user_id", user_id).order("created_at", desc=True).limit(5).execute()
        
        recent_activity = []
        if activity_res.data:
            for act in activity_res.data:
                # Basic time formatting (e.g. "2 min ago" is complex, so we'll just format relative to now on frontend, returning ISO string here)
                recent_activity.append({
                    "action": act["action"],
                    "entity": act["entity"],
                    "type": act["type"],
                    "time": act["created_at"]
                })
                
        # Format the generic Vault Growth data
        # For simplicity, returning static month labels but a flat line at 0 or the current count for the current month.
        current_month = datetime.datetime.now().strftime("%b")
        vaultGrowthData = [
          { "month": "Sep", "assets": 0 },
          { "month": "Oct", "assets": 0 },
          { "month": "Nov", "assets": 0 },
          { "month": "Dec", "assets": 0 },
          { "month": "Jan", "assets": 0 },
          { "month": current_month, "assets": encrypted_assets },
        ]
        
        # Format distribution
        assetDistribution = [
          { "name": "Secure Vaults / Profiles", "value": encrypted_assets > 0 and 100 or 0 },
          { "name": "Financial Accounts", "value": 0 },
          { "name": "Legal Documents", "value": 0 }
        ]

        return {
            "status": "success",
            "metrics": {
                "encrypted_assets": encrypted_assets,
                "verified_documents": verified_documents,
                "pending_triggers": 0,
                "fraud_alerts": 0,
                "notarizations": notarizations,
                "active_nominees": active_nominees
            },
            "recent_activity": recent_activity,
            "charts": {
                "vault_growth": vaultGrowthData,
                "asset_distribution": assetDistribution
            }
        }
        
    except Exception as e:
        print(f"Error fetching dashboard summary: {str(e)}")
        raise HTTPException(status_code=500, detail="Failed to load dashboard data generated by real services")
